package org.home.data.theory.alloc;

/**
 * Честность источника кривой (ТЗ 65 §3.3). Обязательное поле: если хотя бы одна
 * кривая пула помечена {@link #IN_SAMPLE}, весь отчёт помечается как верхняя
 * граница, а не оценка.
 */
public enum CurveKind {

    /** Параметры стратегии выбраны со знанием всей истории → результат — верхняя граница. */
    IN_SAMPLE,

    /** Кривая получена walk-forward → результат интерпретируется как оценка. */
    WALK_FORWARD,

    /** Живой P&L → приоритетный источник. */
    LIVE
}
