package org.home.data.trade;

/**
 * Оценка стоимости удержания шорта на 5 дней (фильтр дорогого шорта, doc 54 §4 / doc 55 §3.2).
 * В live доступна только текущая ставка из тикера — она предсказывает накопленную за 5д (корр 0.812,
 * совпадение решения 94%, `s5_prelaunch`). Для шорта funding>0 = получаем; дорогой шорт = сумма < −1.5%.
 */
public interface FundingSource {
    /** Оценка накопленного funding за 5 дней удержания шорта (доля; отрицательная = шорт платит). */
    double estimate5dFunding(String base) throws Exception;
}
