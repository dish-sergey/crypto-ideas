package org.home.data.trade;

/**
 * Оценка стоимости удержания шорта на 5 дней — фильтр дорогого шорта
 * (док. 54 §4 / док. 55 §3.2). Для шорта {@code funding > 0} значит «получаем»;
 * дорогой шорт — сумма ниже −1.5%.
 *
 * ⚠️ <b>Обоснование фильтра исправлено (док. 141).</b> Прежняя формулировка
 * гласила: «текущая ставка предсказывает накопленную за 5 дней, корр 0.812,
 * совпадение решения 94%». Эта величина измерена на ВОСЬМИЧАСОВОМ фондировании
 * Binance (`s5_prelaunch`) и на Kraken не проверялась — там коллектор собирал
 * два символа из 274. После бэкфилла всей вселенной (2.25 млн часовых ставок)
 * измерено прямо: <b>корреляция 0.317, R² = 0.10</b>. Текущая ставка объясняет
 * десятую часть дисперсии, а не четыре пятых.
 *
 * <b>Фильтр от этого не перестал работать — но держится он на другом.</b> Не на
 * предсказуемости, а на форме распределения: медиана стоимости удержания
 * −0.10%, первый процентиль −7.9%. Один процент окон стоит дороже всей премии
 * события, и даже слабый признак ловит этот край — отсечённые окна стоят в
 * среднем −1.355% против +0.121% у пропущенных, экономия 0.24 п.п. на событие.
 *
 * <b>И граница применимости, которой раньше не было:</b> ужесточать порог
 * вредно. При −0.5% фильтр выбрасывает треть событий, и потерянная премия
 * перевешивает экономию — итог на кандидата хуже, чем совсем без фильтра.
 * Пологий оптимум лежит около −3%, нынешние −1.5% отдают ему два с половиной
 * процента итога (док. 141 §3).
 */
public interface FundingSource {
    /** Оценка накопленного funding за 5 дней удержания шорта (доля; отрицательная = шорт платит). */
    double estimate5dFunding(String base) throws Exception;
}
