package org.home.data.revx.replay;

import java.util.List;

/**
 * Кто решает, исполнилась ли наша заявка. Единственная неизвестная стенда.
 *
 * <h2>Почему это отдельный интерфейс</h2>
 *
 * Всё остальное в {@link SimVenue} — учёт заявок, остатки, резервы, семантика
 * замены, 422 — проверено повтором живого журнала: при верных исполнениях
 * котировки сходятся с живым на 99.92% (61 542 тика из 61 592, 05.09.2026).
 * Значит любое расхождение стенда с реальностью относится сюда, а не
 * размазывается по десятку подозреваемых. Ради этого повтор и делался.
 *
 * <h2>Три реализации, и у каждой своя роль</h2>
 *
 * <ul>
 *   <li>{@link RecordedFillModel} — КОНТРОЛЬ. Исполнения берутся из записи, не
 *       предсказываются. Ничего не прогнозирует и при других параметрах бота
 *       бессмыслен: заявка, которой рынок бы не коснулся, «исполнится», потому
 *       что так было у другого бота. Нужен, чтобы доказать исправность всего
 *       остального;</li>
 *   <li>{@code MarketFillModel} — РАБОЧАЯ. Очередь перед заявкой по видимой
 *       книге, перехват внутри спреда, заявка вне пяти уровней не исполняется.
 *       Ею и меряется;</li>
 *   <li>{@code TouchFillModel} — ВЕРХНЯЯ ГРАНИЦА. «Цена коснулась — меня
 *       исполнили», то самое наивное допущение, от которого ТЗ §4.3
 *       предостерегает. Само по себе оно неверно, но как заведомо завышенная
 *       оценка полезно: результат стратегии обязан лежать между ним и рабочей
 *       моделью, и если даже верхняя граница не даёт прибыли — считать дальше
 *       незачем.</li>
 * </ul>
 *
 * ⚠️ Прогноз без вилки не отдавать. Одно число от рабочей модели выглядит
 * убедительнее, чем оно есть: модель очереди держится на допущениях, которые
 * живыми заявками не проверялись.
 */
public interface FillModel {

    /** Наша заявка, стоящая в книге. */
    record Resting(String id, boolean buy, double price, double size, long placedMs) {
    }

    /** Исполнение, случившееся по заявке. */
    record Filled(String orderId, double qty, double price) {
    }

    /**
     * Что исполнилось к моменту {@code nowMs}.
     *
     * Вызывается перед КАЖДЫМ ответом площадки: бот узнаёт об исполнении из
     * списка активных и из {@code GET /orders/{id}}, и порядок «сначала событие,
     * потом ответ» обязан совпадать с живым.
     */
    List<Filled> advance(long nowMs, List<Resting> resting);

    /** Заявка встала в книгу. Модели очереди нужен момент входа. */
    default void placed(Resting order) {
    }

    /** Заявка ушла из книги — отменена или заменена. */
    default void cancelled(String orderId) {
    }

    /** Как назвать модель в отчёте. */
    String describe();
}
