package org.home.data.revx.replay;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.Statement;

/**
 * Соединение с базой стенда, настроенное на ЧТЕНИЕ БОЛЬШИХ КУСКОВ.
 *
 * <h2>Что тормозило</h2>
 *
 * Обход упирался не в процессор, а в диск. Причина в том, что индекс
 * {@code idx_revx_book_recv(symbol, t_recv_ms)} покрывает только отбор, а
 * запрос тянет двадцать одну колонку стакана ({@code bp1..aq5}). Значит после
 * поиска по индексу на КАЖДУЮ строку идёт отдельное обращение к странице с
 * самой строкой: около 57 тысяч случайных чтений на пару-сутки, то есть больше
 * пяти миллионов за прогон по шести парам и шестнадцати суткам.
 *
 * Делать индекс покрывающим нельзя: он повторил бы почти всю таблицу и удвоил
 * файл. Правильный ответ — чтобы файл лежал в памяти, а не на диске.
 *
 * <h2>Почему память была занята не тем</h2>
 *
 * На машине 31.8 ГБ, база 4.16 ГБ — она помещается в файловый кэш целиком. Но
 * прогоны запускались с {@code -Xmx10g}, и куча отбирала память у кэша: при
 * 7.9 ГБ свободных десятигигабайтная куча не оставляла места ни базе, ни
 * страницам. Куче столько не нужно — {@link MarketData} держит в памяти сутки
 * по одной паре, это единицы мегабайт. Отсюда {@code -Xmx4g} в скриптах
 * прогонов: не экономия, а возврат памяти тому, кто ею действительно
 * распорядится лучше.
 *
 * <h2>Что делают PRAGMA</h2>
 *
 * <ul>
 *   <li>{@code mmap_size} — читать через отображение файла в память, без
 *       системного вызова и лишнего копирования на каждую страницу. Отображение
 *       ОБЩЕЕ для процесса, поэтому двенадцать потоков не занимают память
 *       двенадцать раз;</li>
 *   <li>{@code cache_size} — отрицательное значение задаёт размер в килобайтах,
 *       а не в страницах. 64 МБ на соединение против стандартных двух;</li>
 *   <li>{@code temp_store=MEMORY} — сортировки не уезжают во временные файлы;</li>
 *   <li>{@code query_only} — страховка поверх {@code mode=ro}.</li>
 * </ul>
 *
 * ⚠️ PRAGMA молча игнорируются, если их не понял драйвер, поэтому
 * {@link #mmapApplied(Connection)} умеет проверить фактическое значение. Молча
 * не сработавшая оптимизация хуже отсутствующей: она объясняет, почему «уже
 * ускорено», когда ничего не изменилось.
 */
public final class StandDb {

    private static final Logger log = LoggerFactory.getLogger(StandDb.class);

    /**
     * Сколько файла отображать в память. Восемь гигабайт с запасом покрывают
     * нынешние 4.16 ГБ базы: отображение резервирует адресное пространство, а не
     * физическую память, поэтому запас ничего не стоит.
     */
    private static final long MMAP_BYTES = 8L * 1024 * 1024 * 1024;

    private StandDb() {
    }

    /** Соединение только на чтение, настроенное под потоковое чтение таблиц. */
    public static Connection open(String path) throws Exception {
        Connection c = DriverManager.getConnection("jdbc:sqlite:file:" + path + "?mode=ro");
        try (Statement st = c.createStatement()) {
            st.execute("PRAGMA mmap_size=" + MMAP_BYTES);
            st.execute("PRAGMA cache_size=-65536");
            st.execute("PRAGMA temp_store=MEMORY");
            st.execute("PRAGMA query_only=ON");
        } catch (Exception e) {
            // Настройки — ускорение, а не условие работы: без них читается так же,
            // только медленнее. Ронять из-за них прогон нельзя.
            log.warn("настройки чтения базы стенда не применились: {}", e.getMessage());
        }
        return c;
    }

    /** Сколько байт отображено на самом деле; 0 — отображение не работает. */
    public static long mmapApplied(Connection c) {
        try (Statement st = c.createStatement();
             var rs = st.executeQuery("PRAGMA mmap_size")) {
            return rs.next() ? rs.getLong(1) : 0;
        } catch (Exception e) {
            return 0;
        }
    }
}
