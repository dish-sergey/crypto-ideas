package org.home.data.revx.place;

import org.home.data.revx.layout.DesiredOrder;

import java.util.List;

/**
 * КАК ПРИВЕСТИ КНИГУ к желаемой расстановке. Второй сменный узел.
 *
 * <h2>Зачем отделено от расстановки</h2>
 *
 * Расстановка говорит, где заявки должны стоять. Но между «должны» и «стоят»
 * лежит цена движения: у площадки 10 замен в секунду на ВЕСЬ счёт, и боты делят
 * их вшестером. Значит идеальное следование за расстановкой недостижимо, а
 * насколько это стоит — вопрос измеримый, и мерить его надо отдельно от вопроса
 * «где стоять».
 *
 * Отсюда две версии: {@link InstantPlacer} двигает всё сразу и служит верхней
 * границей, {@link RateLimitedPlacer} двигает одну заявку за тик — то, что
 * работает на живых ботах. Разница между ними и есть цена задержки.
 *
 * <h2>Контракт</h2>
 *
 * Чистая функция: ни площадки, ни журнала. Возвращает план; выполняет его
 * исполнитель, он же тратит бюджет постановок и проверяет предохранители. План
 * может быть пустым — это законный ответ «сейчас ничего не трогаем».
 */
public interface Placer {

    /** Имя версии — попадает в журнал, чтобы прогоны не перепутались. */
    String name();

    /**
     * @param desired как должно быть
     * @param resting как есть сейчас, по одной записи на слот
     * @param nowMs   текущее время: нужно для пауз после отказов
     * @return что сделать в этот тик
     */
    List<Action> plan(List<DesiredOrder> desired, List<RestingOrder> resting, long nowMs);
}
