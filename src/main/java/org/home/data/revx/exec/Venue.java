package org.home.data.revx.exec;

/**
 * Площадка глазами котировщика: всё, что {@link QuoteLoop} умеет с ней делать.
 *
 * <h2>Зачем интерфейс</h2>
 *
 * Котировку до сих пор считали ДВА разных кода: {@link QuoteLoop} в живом боте и
 * {@code revx.sim.Quoter} на стенде. Пока их два, они расходятся молча, и
 * проверять что-либо на стенде бессмысленно — «на проверку одно, а у живого
 * другое». Отсюда правило: решение принимает ОДИН код, а различаться реализации
 * обязаны только здесь, на границе с площадкой.
 *
 * Живая реализация — {@link TradeClient}, шлёт настоящие HTTP-запросы на
 * Revolut X. Стендовая — {@link org.home.data.revx.sim.SimVenue}, отвечает на те
 * же запросы по записанным данным. {@link QuoteLoop} между ними неотличим:
 * он один и тот же байт в байт.
 *
 * <h2>Почему обмен идёт строками JSON</h2>
 *
 * Соблазн отдать типизированные объекты велик, но тогда стенд перестанет
 * проверять СБОРКУ тела запроса и РАЗБОР ответа — а именно там жили самые
 * дорогие ошибки: имя поля с идентификатором различается между ответами
 * ({@code venue_order_id} против {@code id}), замена возвращает новый
 * идентификатор, 422 не означает, что замены не было. Стенд обязан гонять тот же
 * парсер, что и живой, иначе он проверяет не бота, а свою модель бота.
 */
public interface Venue {

    /** Ответ площадки. {@code body} — сырой JSON, как пришёл. */
    record Response(int status, String body, long latencyMs) {

        public boolean ok() {
            return status >= 200 && status < 300;
        }

        /**
         * Ответа не было: запрос ушёл, результат неизвестен.
         *
         * ⚠️ Это НЕ отказ. Замена могла пройти на площадке, а наследник —
         * остаться без хозяина: за всю историю такое случилось один раз на
         * 355 040 замен (бот A, 03.09.2026, таймаут). Судьбу заявки после этого
         * узнают только из {@link #activeOrders()}.
         */
        public boolean lost() {
            return status < 0;
        }
    }

    /** Открытые заявки. ⚠️ Единственный надёжный источник правды о судьбе заявки. */
    Response activeOrders();

    /** Остатки счёта. Читать надо {@code available}, а не {@code total}. */
    Response balances();

    /** Одна заявка по идентификатору — в том числе уже неактивная. */
    Response order(String id);

    /** Постановка. Тратит суточный лимит: 1000 штук на весь счёт, другого нет. */
    Response place(String json);

    /** Замена цены. Суточного потолка нет — перевыставление идёт сюда. */
    Response replace(String id, String json);

    /** Отмена. Ответ 204 без тела. */
    Response cancel(String id);
}
