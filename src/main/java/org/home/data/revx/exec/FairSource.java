package org.home.data.revx.exec;

/**
 * Источник справедливой цены — третий и последний канал связи котировщика с
 * внешним миром, наряду с {@link Venue} и {@link Clock}.
 *
 * Живая реализация — {@link StandReader}, читает базу стенда. Повторная —
 * {@link org.home.data.revx.replay.ReplayFair}, отдаёт цену, записанную в
 * {@code exec_quote} живым ботом на этом самом тике.
 *
 * ⚠️ Подменять надо именно ЦЕНУ, а не пересчитывать её заново из книги. Живой
 * бот принимал решение по конкретному числу, и если повтор возьмёт другое —
 * пусть даже более правильное, — сверка «один в один» становится невозможной:
 * разойдутся котировки, а причину придётся искать между двумя вычислениями
 * справедливой цены вместо самой логики бота.
 */
public interface FairSource {

    /**
     * Последняя справедливая цена по базовой валюте.
     *
     * @param lookbackMs насколько старую цену ещё принимать
     */
    StandReader.Fair latest(String base, long lookbackMs);
}
