package org.home.data.revx.exec;

import java.util.UUID;

/**
 * Метка РУЧНОЙ заявки — той, что поставлена человеком через {@code --revx-order}.
 *
 * <h2>Зачем отдельная метка, а не метка бота</h2>
 *
 * Ручная заявка обязана вести себя противоположно двум разным механизмам, и
 * ровно поэтому ни «метка бота», ни «без метки» не годятся:
 *
 * <ul>
 *   <li><b>стоп-кран обязан её снимать.</b> {@link Panic} по умолчанию снимает
 *       только заявки своего бота — иначе аварийная остановка одного убивала бы
 *       заявки соседей на общем счёте. Безымянная заявка для него чужая:
 *       15.09.2026 две ручные заявки висели в книге, аудит их видел, а паника
 *       ответила «открытых заявок нет» и вышла с успехом (задача A50);</li>
 *   <li><b>котировщик обязан её НЕ трогать.</b> Дай ей метку бота — и
 *       {@link QuoteLoop#reconcile} либо снимет её как хвост, либо усыновит в
 *       слот и начнёт двигать заменами. А смысл {@code --revx-order} прямо
 *       обратный: выйти из позиции по заданной цене, и заявка должна остаться
 *       стоять там, где поставлена.</li>
 * </ul>
 *
 * ⚠️ **Префикс обязан быть шестнадцатеричным.** Площадка принимает
 * {@code client_order_id} только как валидный UUID (закреплено в
 * {@code OrderProbeIdsTest}), а в UUID допустимы лишь цифры {@code 0-9a-f}.
 * Буквы {@code a}–{@code f} заняты шестью ботами, поэтому свободны только
 * цифры; {@code 0} выбран владельцем 16.09.2026: восемь нулей ни с одним ботом не
 * пересекаются и в случайном UUID практически не встречаются.
 *
 * ⚠️ Владелец 16.09.2026 просил префикс {@code zzzzzzzzz-}; он невозможен по
 * этой же причине — {@code z} не шестнадцатеричная цифра, и такая заявка до
 * книги не дойдёт. Замысел «метка, про которую сразу видно, что она не бота»
 * сохранён.
 */
public final class ManualTag {

    /** Первый блок UUID у ручной заявки. */
    public static final String PREFIX = "00000000";

    private ManualTag() {
    }

    /** Новый идентификатор ручной заявки: валидный UUID с нашей меткой. */
    public static String newClientOrderId() {
        return PREFIX + UUID.randomUUID().toString().substring(PREFIX.length());
    }

    /**
     * Ручная ли это заявка.
     *
     * {@code null} означает «не знаем», и такая заявка ручной НЕ считается: у
     * площадки безымянными приходят в том числе заявки, поставленные владельцем
     * в приложении Revolut, а их стоп-кран трогать не должен.
     */
    public static boolean is(String clientOrderId) {
        return clientOrderId != null && clientOrderId.toLowerCase().startsWith(PREFIX);
    }
}
