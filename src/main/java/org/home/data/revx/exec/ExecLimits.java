package org.home.data.revx.exec;

/**
 * Жёсткие пределы исполнителя. **В КОДЕ, А НЕ В КОНФИГЕ** — прямое требование
 * ТЗ §6, и требование осмысленное: конфиг правится на живом сервере одной
 * командой, в спешке и без ревью, а именно в спешке и ставят лишний ноль.
 * Чтобы поднять эти числа, нужно изменить исходник, собрать и выкатить — то есть
 * пройти те же ворота, что и любое изменение логики.
 *
 * Числа выбраны под ЗАДАЧУ МИКРО-LIVE, а не под торговлю. Смысл этапа —
 * измерить долю предсказанных исполнений (док. 91 §3), и для этого хватает
 * заявок по доллару. P&L на таких размерах не значим и целью не является.
 */
public final class ExecLimits {

    private ExecLimits() {
    }

    /**
     * Потолок одной заявки. Прогноз исполнений почти не зависит от размера в
     * диапазоне $1–$5 (534 против 538 за окно, док. 91 §3), поэтому запас до $10
     * нужен лишь на случай округлений, а не для роста.
     */
    public static final double MAX_ORDER_NOTIONAL_USDC = 10.0;

    /**
     * Потолок суммарной экспозиции: стоящие заявки плюс инвентарь. На счёте
     * лежит порядка $20 двумя валютами, и предел выставлен так, чтобы ошибка в
     * размере упёрлась в него раньше, чем в остаток счёта.
     */
    public static final double MAX_TOTAL_EXPOSURE_USDC = 25.0;

    /**
     * Постановок в сутки. У площадки 1000 (`POST /orders`), и это единственный
     * жёсткий ресурс: перевыставление идёт через `PUT` без суточного потолка.
     * 800 оставляет запас на повторы и на ручные проверки.
     */
    public static final int MAX_PLACEMENTS_PER_DAY = 800;

    /**
     * Предохранитель от зацикливания: если за минуту потребовалось больше
     * стольких перевыставлений, что-то не так с расчётом цены, и лучше встать.
     * Наблюдённая норма — около 14 в минуту (19 951 в сутки).
     */
    public static final int MAX_REPLACES_PER_MINUTE = 120;

    /**
     * Максимальный убыток ОТ ТОРГОВЛИ, после которого котирование выключается.
     *
     * Считается против buy & hold, а не против стартовой стоимости счёта:
     * {@code (USDC − USDC₀) + (BTC − BTC₀) × цена}. Иначе падение биткойна на
     * пять процентов выглядело бы как торговый убыток и глушило бы стенд на
     * ровном месте — а это рыночный риск стартовой позиции, к качеству
     * котирования отношения не имеющий.
     *
     * Доллар на счёте в $28 при заявках по доллару — это уже не шум, а признак
     * того, что что-то систематически не так.
     */
    public static final double MAX_TRADING_LOSS_USDC = 1.0;

    /**
     * Любая ненулевая комиссия останавливает торговлю.
     *
     * Не потому, что она сразу убыточна — измеренный край держит до 0.084%, —
     * а потому что maker 0% это ПРОМО молодой площадки, и его отмена меняет
     * не параметр, а экономику конструкции. Такое решение принимает человек,
     * а не цикл, который просто продолжит торговать по новым правилам.
     */
    public static final double MAX_FEE_USDC = 0.0;

    /** Проверка размера заявки перед отправкой. */
    public static boolean orderAllowed(double notionalUsdc) {
        return notionalUsdc > 0 && notionalUsdc <= MAX_ORDER_NOTIONAL_USDC;
    }

    public static boolean exposureAllowed(double totalUsdc) {
        return totalUsdc <= MAX_TOTAL_EXPOSURE_USDC;
    }

    public static String describe() {
        return """
                Жёсткие пределы (в коде, менять только пересборкой):
                  заявка не больше       %.2f USDC
                  экспозиция не больше   %.2f USDC
                  постановок в сутки     %d (у площадки 1000)
                  перевыставлений в мин  %d""".formatted(
                MAX_ORDER_NOTIONAL_USDC, MAX_TOTAL_EXPOSURE_USDC,
                MAX_PLACEMENTS_PER_DAY, MAX_REPLACES_PER_MINUTE);
    }
}
