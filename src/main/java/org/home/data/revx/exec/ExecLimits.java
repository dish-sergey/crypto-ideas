package org.home.data.revx.exec;

/**
 * Жёсткие пределы исполнителя. **В КОДЕ, А НЕ В КОНФИГЕ** — прямое требование
 * ТЗ §6, и требование осмысленное: конфиг правится на живом сервере одной
 * командой, в спешке и без ревью, а именно в спешке и ставят лишний ноль.
 * Чтобы поднять эти числа, нужно изменить исходник, собрать и выкатить — то есть
 * пройти те же ворота, что и любое изменение логики.
 *
 * Числа выбраны под ЗАДАЧУ МИКРО-LIVE, а не под торговлю. Смысл этапа —
 * измерить долю предсказанных исполнений (док. 91 §3), и для этого хватает
 * заявок по доллару. P&L на таких размерах не значим и целью не является.
 */
public final class ExecLimits {

    private ExecLimits() {
    }

    /**
     * Сколько ботов делят один аккаунт. Суточный потолок постановок у площадки
     * общий на ВЕСЬ аккаунт (док. 74), а не на процесс, поэтому каждому боту
     * достаётся своя доля. Число здесь, а не в конфиге, по той же причине, что и
     * всё остальное в этом классе.
     *
     * С 02.09.2026 ботов три: A и C отличаются ТОЛЬКО отступом (10 и 14 б.п.) и
     * вдвоём дают двухточечную оценку κ на живых данных — величины, которая
     * задаёт δ* и весь выбор пар, но живьём не мерилась ни разу (док. 132 §5).
     * B остаётся с механизмами против A.
     */
    public static final int BOTS_SHARING_ACCOUNT = 3;

    /**
     * Потолок одной заявки. Прогноз исполнений почти не зависит от размера в
     * диапазоне $1–$5 (534 против 538 за окно, док. 91 §3), поэтому запас до $10
     * нужен лишь на случай округлений, а не для роста.
     */
    public static final double MAX_ORDER_NOTIONAL_USDC = 10.0;

    /**
     * Потолок суммарной экспозиции: стоящие заявки плюс инвентарь. На счёте
     * лежит порядка $20 двумя валютами, и предел выставлен так, чтобы ошибка в
     * размере упёрлась в него раньше, чем в остаток счёта.
     */
    public static final double MAX_TOTAL_EXPOSURE_USDC = 30.0;

    /**
     * Постановок в сутки, ПО БОТАМ. У площадки 1000 (`POST /orders`) на весь
     * аккаунт, и это единственный жёсткий ресурс: перевыставление идёт через
     * `PUT` без суточного потолка.
     *
     * Делить поровну неправильно, потому что боты расходуют бюджет неодинаково.
     * Замер за 02.09.2026: у A 48 исполнений за 6.6 ч (каждое исполнение
     * съедает заявку и требует новой постановки), у B шесть, у C семь.
     *
     * С 05.09.2026 бот C переводится с 14 на 7 б.п. и получает БОЛЬШЕ ВСЕХ:
     * расход постановок идёт за исполнениями, а на 7 б.п. лестница отступов
     * обещает около 100 в сутки против 25 у A. B на SOL расходует меньше всех
     * (12 постановок за 17 часов), у него и берём запас. Сумма
     * 300 + 200 + 400 = 900 из 1000 оставляет сотню на повторы и ручные
     * проверки — без неё зонд или ручная заявка вышли бы за потолок площадки.
     *
     * Прежняя раскладка была A 400, B 300, C 200 — под контроль на A и самый
     * широкий отступ у C.
     *
     * ⚠️ Число 400 у бота A проверки практикой не проходило до 04.09.2026:
     * счётчик обнулялся при каждом запуске, и предел не действовал ни разу.
     * В первый же день настоящего учёта A упёрся в него — но упёрся расходом,
     * набранным пересечением стакана, а не торговлей.
     *
     * Карта в КОДЕ, а не в конфиге, по той же причине, что и остальные пределы
     * этого класса: поднять число можно только пересборкой и выкаткой.
     */
    private static final java.util.Map<String, Integer> PLACEMENTS_BY_BOT =
            java.util.Map.of("a", 300, "b", 200, "c", 400);

    /**

    /**
     * Сколько постановок в сутки положено этому боту.
     *
     * ⚠️ Незнакомая метка получает САМУЮ МАЛУЮ долю из карты, а не среднюю.
     * Иначе опечатка в {@code --revx.exec.bot-id} молча выдавала бы боту бюджет
     * БОЛЬШЕ настроенного, и суммарный расход по аккаунту вышел бы за потолок
     * площадки — ровно тот класс тихой ошибки, ради которого пределы и живут в
     * коде.
     */
    public static int maxPlacementsPerDay(String botId) {
        String key = botId == null || botId.isBlank()
                ? "" : botId.trim().substring(0, 1).toLowerCase(java.util.Locale.ROOT);
        return PLACEMENTS_BY_BOT.getOrDefault(key,
                PLACEMENTS_BY_BOT.values().stream().min(Integer::compareTo).orElse(100));
    }

    /**
     * Предохранитель от зацикливания: если за минуту потребовалось больше
     * стольких перевыставлений, что-то не так с расчётом цены, и лучше встать.
     * Наблюдённая норма — около 14 в минуту (19 951 в сутки).
     */
    public static final int MAX_REPLACES_PER_MINUTE = 120;

    /**
     * Максимальный убыток ОТ ТОРГОВЛИ, после которого котирование выключается.
     *
     * Считается против buy & hold, а не против стартовой стоимости счёта:
     * {@code (USDC − USDC₀) + (BTC − BTC₀) × цена}. Иначе падение биткойна на
     * пять процентов выглядело бы как торговый убыток и глушило бы стенд на
     * ровном месте — а это рыночный риск стартовой позиции, к качеству
     * котирования отношения не имеющий.
     *
     * Доллар на счёте в $28 при заявках по доллару — это уже не шум, а признак
     * того, что что-то систематически не так.
     */
    public static final double MAX_TRADING_LOSS_USDC = 1.0;

    /**
     * Любая ненулевая комиссия останавливает торговлю.
     *
     * Не потому, что она сразу убыточна — измеренный край держит до 0.084%, —
     * а потому что maker 0% это ПРОМО молодой площадки, и его отмена меняет
     * не параметр, а экономику конструкции. Такое решение принимает человек,
     * а не цикл, который просто продолжит торговать по новым правилам.
     */
    public static final double MAX_FEE_USDC = 0.0;

    /** Проверка размера заявки перед отправкой. */
    public static boolean orderAllowed(double notionalUsdc) {
        return notionalUsdc > 0 && notionalUsdc <= MAX_ORDER_NOTIONAL_USDC;
    }

    public static boolean exposureAllowed(double totalUsdc) {
        return totalUsdc <= MAX_TOTAL_EXPOSURE_USDC;
    }

    public static String describe(String botId) {
        return """
                Жёсткие пределы (в коде, менять только пересборкой):
                  заявка не больше       %.2f USDC
                  экспозиция не больше   %.2f USDC
                  постановок в сутки     %d (у площадки 1000)
                  перевыставлений в мин  %d
                  комиссия не больше     %.2f USDC — иначе стоп
                  торговый убыток        %.2f USDC — иначе стоп (против buy and hold)""".formatted(
                MAX_ORDER_NOTIONAL_USDC, MAX_TOTAL_EXPOSURE_USDC,
                maxPlacementsPerDay(botId), MAX_REPLACES_PER_MINUTE,
                MAX_FEE_USDC, MAX_TRADING_LOSS_USDC);
    }
}
