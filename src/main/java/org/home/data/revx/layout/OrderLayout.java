package org.home.data.revx.layout;

import java.util.List;

/**
 * КАК ДОЛЖНЫ СТОЯТЬ ЗАЯВКИ. Главный сменный узел системы.
 *
 * <h2>Зачем интерфейс</h2>
 *
 * Доход маркет-мейкера почти целиком определяется тем, где и каким объёмом
 * стоят заявки. Всё остальное — учёт, лимиты, восстановление после сбоев —
 * защищает этот выбор, но не создаёт его. Значит именно здесь нужно ставить
 * опыты, и ставить их дёшево: две версии одновременно в дереве, переключение
 * настройкой, сравнение на одних и тех же данных.
 *
 * <h2>Контракт</h2>
 *
 * Реализация обязана быть ЧИСТОЙ ФУНКЦИЕЙ от {@link MarketState}: ни площадки,
 * ни журнала, ни системных часов. Иначе две версии нельзя сравнить — их прогоны
 * разойдутся по причинам, к расстановке отношения не имеющим.
 *
 * Состояние внутри допустимо, но только СВОЁ и только объявленное: например,
 * скользящее окно цен. Такое состояние обязано восстанавливаться из
 * последовательности вызовов, иначе повтор прогона перестанет совпадать сам с
 * собой.
 *
 * <h2>Чего расстановка НЕ делает</h2>
 *
 * Не решает, что отправлять площадке. Возвращённый список — это «как должно
 * быть», а не «что сделать»: приведением занимается {@code Placer}, и именно он
 * решает, стоит ли двигать заявку ради двух базисных пунктов. Пустой список
 * означает «не котировать вовсе» и это законный ответ, а не ошибка.
 */
public interface OrderLayout {

    /** Имя версии — попадает в журнал и в отчёты, чтобы прогоны не перепутались. */
    String name();

    /**
     * @return желаемые заявки; пустой список — не котировать
     */
    List<DesiredOrder> layout(MarketState state);

    /**
     * Исполнение состоялось. Нужно только тем расстановкам, чьи цены зависят от
     * собственной истории сделок (например, пол по себестоимости). Остальным —
     * пустое тело.
     */
    default void onFill(org.home.data.revx.sim.Fill fill) {
    }
}
