package org.home.data.revx.layout;

/**
 * Всё, что расстановка знает о мире на этот тик.
 *
 * <h2>Зачем отдельная запись</h2>
 *
 * Расстановка — то место, от которого доход зависит сильнее всего, и именно его
 * хочется менять чаще прочего. Пока она была размазана по {@code QuoteLoop},
 * каждый опыт означал правку боевого цикла: одна и та же арифметика жила в трёх
 * местах (цены уровней, раздача капитала, гейты), и сравнить две версии можно
 * было только по очереди, пересобирая проект.
 *
 * Эта запись — граница. Всё, что расстановке нужно, приходит через неё; всё, что
 * она решила, уходит списком {@link DesiredOrder}. Ни площадки, ни журнала, ни
 * часов у неё нет, поэтому две версии сравниваются на одних и тех же входах.
 *
 * <h2>Что здесь есть и почему</h2>
 *
 * Справедливая цена, инвентарь и остаток бюджета постановок — то, с чего
 * начинали. К ним пришлось добавить ещё четыре величины, и каждая нужна:
 *
 * <ul>
 *   <li>{@code bookBid}/{@code bookAsk} — без них нельзя не пересечь книгу.
 *       Корзинная справедливая цена на быстром движении обгоняет книгу площадки,
 *       и заявка встаёт на исполнение немедленно: 03.09.2026 из 217 отказов
 *       замены 139 пришли с {@code post_only_immediate_match};</li>
 *   <li>{@code quoteStep} — шаг цены. Сетка мельче тика вырождается: у ENA тик
 *       6.01 б.п. при шаге сетки 2, и три уровня стояли на одной цене;</li>
 *   <li>{@code cash} — касса своя, а не общая. На счёте лежат деньги шести
 *       ботов, и раздавать по уровням можно только своё;</li>
 *   <li>{@code referenceSpreadPct} — ширина опорной книги, мера неопределённости
 *       цены. Именно на неё раздвигается отступ вместо остановки котирования.</li>
 * </ul>
 *
 * <h2>Пределы приходят как ДАННЫЕ</h2>
 *
 * {@code maxOrderNotional}, {@code maxExposure} и {@code minNotional} лежат здесь
 * не для того, чтобы расстановка их соблюдала по чести, а чтобы не выдавала
 * заведомо непроходимых заявок. Проверяет их всё равно {@code QuoteLoop}, и
 * проверяет заново: ТЗ §6 держит предохранители в коде исполнителя, и никакая
 * сменная расстановка не должна получить возможность их обойти.
 *
 * @param fair               справедливая цена по корзине
 * @param referenceSpreadPct ширина опорной книги в процентах
 * @param bookBid            лучший бид площадки; 0 — книга неизвестна
 * @param bookAsk            лучший аск площадки; 0 — книга неизвестна
 * @param inventory          СВОЯ позиция в базовой валюте
 * @param cash               СВОЯ касса в валюте котировки
 * @param drift              относительный дрейф цены за окно; 0 — выключен
 * @param budgetPressure     дефицит постановок 0…1; 0 — бюджета вдоволь
 * @param quoteStep          шаг цены площадки
 * @param baseStep           шаг количества площадки
 * @param minNotional        минимальный номинал заявки
 * @param maxOrderNotional   потолок номинала одной заявки
 * @param maxExposure        потолок суммарной экспозиции бота
 */
public record MarketState(
        double fair,
        double referenceSpreadPct,
        double bookBid,
        double bookAsk,
        double inventory,
        double cash,
        double drift,
        double budgetPressure,
        double quoteStep,
        double baseStep,
        double minNotional,
        double maxOrderNotional,
        double maxExposure) {

    /** Есть ли вообще с чем работать: без цены расстановка бессмысленна. */
    public boolean usable() {
        return fair > 0;
    }
}
