package org.home.data.revx.layout;

import org.home.data.revx.sim.Side;

/**
 * Одна заявка так, как её хочет видеть расстановка.
 *
 * Это ЖЕЛАЕМОЕ состояние, а не команда. Расстановка не знает, что сейчас стоит в
 * книге, и знать не должна: её дело — сказать, как должно быть, а привести к
 * этому книгу — дело {@code Placer}. Разделение нужно ровно затем, чтобы
 * сравнивать способы приведения (мгновенный против ограниченного одной заменой
 * в тик) при одной и той же расстановке.
 *
 * @param side  сторона
 * @param level номер уровня, 0 — ближний к цене; нужен для сопоставления с уже
 *              стоящими заявками и для потолка замен по уровням
 * @param price цена, уже приведённая к шагу площадки
 * @param size  количество в базовой валюте, уже приведённое к шагу
 */
public record DesiredOrder(Side side, int level, double price, double size) {

    public double notional() {
        return price * size;
    }
}
