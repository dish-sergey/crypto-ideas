package org.home.data.revx.sim;

/**
 * СГЛАЖИВАНИЕ КУРСА USDC/USD ПО ВРЕМЕНИ (задача A45).
 *
 * <h2>Зачем</h2>
 *
 * Курс мы считаем медианой подразумеваемых оценок по парам, и он шумит: шаг за
 * минуту 1.77 б.п. при НУЛЕ у прямой книги площадки (замер 14.09.2026, четверо
 * суток, 34 382 точки). Каждый скачок заставляет ботов переставлять заявки
 * вслед за движением, которого ни в одной книге нет, и тратит общий суточный
 * лимит постановок.
 *
 * Сглаживание убирает дёрганье и НЕ ТРОГАЕТ УРОВЕНЬ — в отличие от перехода на
 * прямую книгу, который сдвинул бы все цены на 5–6 б.п. Это разные вопросы, и
 * решать их надо порознь.
 *
 * <h2>Почему вес по времени, а не по числу тиков</h2>
 *
 * Тики идут неравномерно: на быстром ярусе раз в секунду, на медленном раз в
 * пятнадцать, а после простоя сбора — раз в минуту. Постоянный коэффициент
 * означал бы разное сглаживание в плотные и редкие минуты, то есть настройку,
 * которая меняется сама по себе.
 *
 * ⚠️ Разрыв больше {@link #GAP_MS} сбрасывает состояние: после простоя старое
 * значение курса не «догоняется» — оно уже не имеет отношения к рынку.
 */
public final class RateSmoother {

    /** Разрыв, после которого сглаживание начинается заново, мс. */
    public static final long GAP_MS = 600_000;

    private final double halfLifeSec;
    private double value;
    private long tsMs;

    public RateSmoother(double halfLifeSec) {
        this.halfLifeSec = Math.max(1e-6, halfLifeSec);
    }

    /**
     * Следующее значение сглаженного курса.
     *
     * @param tsMs время наблюдения; ход назад считается разрывом
     * @param rate сырой курс (медиана); неположительный оставляет состояние как есть
     */
    public double next(long tsMs, double rate) {
        if (!(rate > 0)) {
            return value;
        }
        if (!(value > 0) || tsMs <= this.tsMs || tsMs - this.tsMs > GAP_MS) {
            value = rate;
            this.tsMs = tsMs;
            return value;
        }
        double a = 1 - Math.exp(-(tsMs - this.tsMs) / 1000.0 / halfLifeSec);
        value += a * (rate - value);
        this.tsMs = tsMs;
        return value;
    }

    /** Сбросить состояние: следующий вызов начнёт ряд заново. */
    public void reset() {
        value = 0;
        tsMs = 0;
    }
}
