package org.home.data.collectors;

/**
 * Единица работы слоя данных: инкрементальный сбор «с последней записи до сейчас».
 * Идемпотентность обязательна — повторный запуск не должен дублировать строки
 * (все записи через upsert по естественному первичному ключу).
 */
public interface Collector {

    /** Имя для CLI (--collect=имя) и логов. */
    String name();

    /** Инкрементальный сбор. Исключение = сбой этого коллектора, остальные не страдают. */
    void collect() throws Exception;
}
