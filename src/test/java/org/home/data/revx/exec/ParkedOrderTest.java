package org.home.data.revx.exec;

import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Припаркованная заявка переживает перезапуск, торгующая — нет.
 *
 * ⚠️ Свойство не косметическое. Бот стартует с ВЫКЛЮЧЕННЫМ котированием, и
 * первая же сверка сносит всё, что нашла в книге под своей меткой. Без этого
 * различия {@link Park} не экономил бы ни одной постановки: он оставлял бы
 * заявки, а стартующий бот тут же их снимал. Найдено при выкатке 07.09.2026 —
 * до неё вся парковка была бы украшением.
 *
 * Смысл различия: заявка в пяти процентах от цены — не позиция, а держатель
 * места. Исполниться она может только на движении в несколько процентов, а
 * вернуть её в работу можно заменой, у которой суточного лимита нет.
 */
class ParkedOrderTest {

    private static final double PCT = QuoteLoop.PARKED_MIN_PCT;

    @Test
    void заявкаНаПятиПроцентахПрипаркована() {
        // Ровно то, что оставляет Park: 5% от цены в обе стороны.
        assertTrue(QuoteLoop.isParked(0.1705 * 0.95, 0.1705, PCT), "покупка на −5%");
        assertTrue(QuoteLoop.isParked(0.1705 * 1.05, 0.1705, PCT), "продажа на +5%");
    }

    @Test
    void рабочаяЗаявкаНеПрипаркована() {
        // Отступ живых ботов — 10-20 б.п., то есть 0.1-0.2%.
        assertFalse(QuoteLoop.isParked(79390.0 * 0.998, 79390.0, PCT),
                "заявка в 20 б.п. от цены обязана сниматься при остановке");
        assertFalse(QuoteLoop.isParked(79390.0 * 1.002, 79390.0, PCT));
    }

    @Test
    void ценаУспеваетСдвинутьсяАЗаявкаОстаётсяПрипаркованной() {
        // Припарковали на 5%, пока бот перезапускался, рынок ушёл на 1.5%
        // в сторону заявки. Осталось 3.5% — всё ещё выше порога.
        double parked = 100.0 * 0.95;
        double moved = 100.0 * 0.985;
        assertTrue(QuoteLoop.isParked(parked, moved, PCT),
                "запас между 5% парковки и 3% порогом обязан переживать ход рынка");
    }

    @Test
    void безНадёжнойЦеныСнимаемВсё() {
        // Неизвестность работает в сторону осторожности: не знаем цены — не
        // оставляем в книге ничего.
        assertFalse(QuoteLoop.isParked(0.16, 0, PCT), "нулевая опора");
        assertFalse(QuoteLoop.isParked(0.16, -1, PCT), "отрицательная опора");
        assertFalse(QuoteLoop.isParked(0, 0.1705, PCT), "нулевая цена заявки");
    }

    @Test
    void порогПаркиНижеРасстоянияПарковки() {
        // Park уводит на 5%, порог 3%. Если порог когда-нибудь поднимут выше
        // расстояния парковки, парковка снова начнёт молча сниматься.
        assertTrue(PCT < 0.05,
                "порог припаркованности " + PCT + " не ниже расстояния парковки 0.05 —"
                        + " Park оставит заявки, а сверка их снимет");
    }
}
