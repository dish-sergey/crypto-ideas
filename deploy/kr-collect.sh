#!/usr/bin/env bash
# Сбор тикера Kraken Futures — СЕРЕДИНА КНИГИ трёх перпов рядом с захватом Бинанса.
#
# ЗАЧЕМ. Протокол 160, блок 1: установлено, что Бинанс опережает Revolut X на 1–4 с
# и контрагент снимает с нас на этом отставании. Вопрос, которого раньше не было:
# **опережает ли Kraken так же**. Если да и с той же величиной, опору можно взять
# оттуда же, где будет стоять хедж, и вся конструкция упрощается до ОДНОЙ внешней
# площадки вместо двух. Сейчас Kraken собирается раз в пять минут — для такого
# замера нужен секундный поток.
#
# ⚠️ Каждый час без записи — дыра навсегда (принцип 4). Разбор потом, захват сейчас.
#
# 🔑 УСТРОЙСТВО ПОВТОРЯЕТ `bnb-collect.sh` ПОСЛЕ ПРАВКИ 17.09.2026, и повторяет
# намеренно: там эти же три грабли стоили 23 часов молчания при живой службе.
#   * подписку держит ФОНОВЫЙ процесс через FIFO, а не `sleep` в конвейере. Иначе
#     смерть websocat не заканчивает итерацию: оболочка ждёт весь конвейер вместе
#     со спящим первым звеном;
#   * `--ping-timeout` рвёт молчащее соединение, `-E` обязателен рядом с пингами —
#     без него websocat сам предупреждает, что пинги «not very effective»;
#   * файл выбирается ПО КАЖДОМУ сообщению из той же отметки `date`, поэтому
#     сессия, пережившая полночь, пишет в правильные сутки, а ночная упаковка не
#     заберёт файл из-под живой записи.
#
# ⚠️ Отметка времени наша, а не биржи, хотя Kraken свою (`time`) присылает. Так и
# надо: мерить мы будем, когда МЫ БЫ узнали. Биржевая остаётся в теле строки, и
# разность двух даёт задержку до площадки — её тоже полезно знать.
#
# Темп замерен 18.09.2026: 8.4 сообщения в секунду на три контракта (BTC 3.8,
# ETH 2.5, SOL 2.1), 644 байта на строку, то есть ~470 МБ в сутки сырого текста —
# столько же, сколько у Бинанса. Жмётся ночью тем же `bnb-prune.sh` с DIR.
set -u
OUT="${OUT:-$HOME/kraken-book}"
PRODUCTS='"PF_XBTUSD","PF_ETHUSD","PF_SOLUSD"'
PING_INTERVAL="${PING_INTERVAL:-20}"
PING_TIMEOUT="${PING_TIMEOUT:-30}"
mkdir -p "$OUT"

FIFO="$(mktemp -u "${TMPDIR:-/tmp}/kr-sub.XXXXXX")"
cleanup() {
    [ -n "${HOLDER:-}" ] && kill "$HOLDER" 2>/dev/null
    rm -f "$FIFO"
}
trap cleanup EXIT

while true; do
    rm -f "$FIFO"
    mkfifo "$FIFO" || { sleep 5; continue; }
    (
        echo "{\"event\":\"subscribe\",\"feed\":\"ticker\",\"product_ids\":[$PRODUCTS]}"
        while :; do sleep 10; done
    ) > "$FIFO" &
    HOLDER=$!

    "$HOME/bin/websocat" -t -E --ping-interval "$PING_INTERVAL" \
        --ping-timeout "$PING_TIMEOUT" "wss://futures.kraken.com/ws/v1" < "$FIFO" \
        | while IFS= read -r line; do
            stamp=$(date -u +"%s%3N %Y-%m-%d")
            printf '%s %s\n' "${stamp% *}" "$line" >> "$OUT/book-${stamp#* }.jsonl"
        done

    kill "$HOLDER" 2>/dev/null
    wait "$HOLDER" 2>/dev/null
    HOLDER=
    echo "$(date -u +%FT%TZ) сессия закончилась, переподключаюсь" >&2
    sleep 2
done
