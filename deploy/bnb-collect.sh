#!/usr/bin/env bash
# Сбор bookTicker Бинанса — СЕРЕДИНА КНИГИ трёх торгуемых пар.
#
# Зачем. Измерено 16.09.2026 (A54): Бинанс идёт впереди Revolut X на 1–4 секунды,
# и контрагент снимает с нас 1.2 б.п. на этом отставании. Чтобы опора перестала
# запаздывать, нужна чужая середина книги в реальном времени.
#
# ⚠️ Архив Бинанса bookTicker для СПОТА НЕ отдаёт — только сделки и свечи. Значит
# середину книги взять задним числом неоткуда, и каждый час без записи — дыра
# навсегда (принцип 4). Поэтому сырой захват сейчас, разбор потом.
#
# ⚠️ Пишем ПРОСТЫМ ТЕКСТОМ, а жмём по ночам отдельным заданием. gzip в конвейере
# держит данные в своём буфере: за 105 секунд и 2400 сообщений файл оставался
# НУЛЕВЫМ, и при перезапуске службы этот буфер пропал бы целиком. 220 МБ в сутки
# сырого текста диск переживёт, потерю данных — нет.
#
# ⚠️ ПОДПИСКА ОБЯЗАТЕЛЬНА ОТДЕЛЬНЫМ СООБЩЕНИЕМ. Адрес вида
# `/stream?streams=a/b` подключается и молчит — ни ошибки, ни данных. Та же
# грабля описана в CLAUDE.md для фьючерсов и повторилась на споте 16.09.2026:
# двадцать секунд тишины вместо потока. Работает `/ws` + SUBSCRIBE.
set -u
OUT="${OUT:-$HOME/binance-book}"
SYMS='"btcusdc@bookTicker","ethusdc@bookTicker","solusdc@bookTicker"'
mkdir -p "$OUT"
while true; do
  DAY=$(date -u +%Y-%m-%d)
  { echo "{\"method\":\"SUBSCRIBE\",\"params\":[$SYMS],\"id\":1}"; sleep 86400; } \
    | timeout 86400 "$HOME/bin/websocat" -t --ping-interval 20 "wss://stream.binance.com:9443/ws" \
    | while IFS= read -r line; do
        # Время ПРИЁМА: у bookTicker спота своей отметки нет, а нам важен момент,
        # когда мы БЫ узнали.
        printf '%s %s\n' "$(date -u +%s%3N)" "$line"
      done >> "$OUT/book-$DAY.jsonl"
  sleep 2
done
