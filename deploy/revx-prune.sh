#!/usr/bin/env bash
# Чистка базы стенда на ARM: снести уже вывезенные и достаточно старые строки.
#
# ЗАЧЕМ. С 10.09.2026 книга по трём торгуемым парам собирается на 20 уровней
# вместо пяти, и база растёт примерно на 525 МБ в сутки против прежних 250.
# На диске ARM свободно 19 ГБ — без чистки это чуть больше месяца до отказа
# записи, а отказ записи здесь означает дыру в данных навсегда (принцип 4:
# книгу задним числом не восстановить).
#
# ГЛАВНАЯ ЗАЩИТА — КУРСОР ВЫГРУЗКИ. Удаляется только то, что УЖЕ уехало в
# инкрементную копию на micro: `rowid <= курсор` из backup-cursor.txt. Курсор
# двигает revx-backup.sh, и только после успешного scp. Поэтому даже если
# выгрузка неделю не работала, чистка не тронет ни одной невывезенной строки —
# она просто ничего не удалит. Проверка по возрасту идёт ВТОРЫМ условием, а не
# первым: возраст без курсора удалил бы данные, которых больше нигде нет.
#
# ⚠️ VACUUM НЕ ДЕЛАЕТСЯ, И ЭТО НАМЕРЕННО. Файл после DELETE не уменьшится, но
# освободившиеся страницы SQLite переиспользует под новые вставки — размер
# выходит на полку, а нам ровно это и нужно. Полный VACUUM на базе в гигабайты
# держит писателя и повторяет инцидент 25-26.08.2026, когда `sqlite3 .backup`
# провисел 34 часа и стоил 33 часов книги безвозвратно. Место ради места того
# не стоит.
#
# Запускать С MICRO (ключ есть только в направлении micro -> ARM), после
# выгрузки: cron `45 4 * * *`, то есть через полтора часа после `15 3`.
set -euo pipefail

ARM_HOST="${ARM_HOST:-130.61.31.216}"
ARM_KEY="${ARM_KEY:-$HOME/.ssh/armkey}"
# 11.09.2026: глубина торгуемых пар поднята с 20 уровней до 50 (охват от ±0.4%
# до ±2.5%, нужен для лестницы на ±2% — задача A12). Прирост вырос с 500 МБ до
# ~890 МБ в сутки, и прежние 21 сутки дали бы 18.7 ГБ при 18 свободных.
# Четырнадцать суток — это ~12.5 ГБ, то есть остаётся запас на случай, когда
# выгрузка сломалась: чистка удаляет ТОЛЬКО вывезенное, поэтому при мёртвой
# выгрузке база просто растёт, и запас измеряется в сутках до отказа записи.
RETAIN_DAYS="${RETAIN_DAYS:-14}"     # 14 суток ~ 12.5 ГБ на полке при 18 ГБ свободных
# ⚠️ ИНЦИДЕНТ 12.09.2026: ЧИСТКА ЗАДУШИЛА СБОРЩИК. Партии по 50 000 строк были
# безобидны, пока строка книги весила байт двести. 11.09 глубина торгуемых пар
# поднята с 20 уровней до 50, строка потяжелела втрое, и та же партия стала
# держать писательский замок соразмерно дольше: чистка шла 6 мин 12 с вместо
# прежних 3 мин 47 с, и ВНУТРИ этого окна у сборщика упали 23 задачи подряд
# (04:47:32 – 04:51:11). Книга перестала обновляться, корзина курса схлопнулась
# до 3 пар при минимуме 8, и все шесть боевых ботов ушли в парковку.
#
# Потеряно около четырёх минут книги — невосполнимо (принцип 4).
#
# Отсюда партия в ТЫСЯЧУ строк. При суточной выработке ~780 тыс. строк это ~780
# транзакций; каждая на тысяче строк идёт десятки миллисекунд, так что при паузе
# в секунду замок занят порядка десятой доли времени, а сборщик пишет девять
# ног в секунду и успевает вклиниться. Чистка растянется минут до двадцати —
# она ночная, ни от чего не зависит и спешить ей некуда.
BATCH="${BATCH:-1000}"               # строк за один DELETE
PAUSE="${PAUSE:-1}"                  # пауза между партиями, секунд
DRY_RUN="${DRY_RUN:-0}"
# Потолок поднят вместе с растяжкой: 780 партий по секунде паузы — это уже
# 13 минут одних пауз, и прежний час оставлял слишком мало запаса.
REMOTE_TIMEOUT="${REMOTE_TIMEOUT:-7200}"

ssh_opts=(-i "$ARM_KEY" -o BatchMode=yes -o ConnectTimeout=20)

ssh "${ssh_opts[@]}" "ubuntu@$ARM_HOST" \
    "flock -n /tmp/revx-prune.lock timeout -k 60 $REMOTE_TIMEOUT env \
     RETAIN_DAYS=$RETAIN_DAYS BATCH=$BATCH PAUSE=$PAUSE DRY_RUN=$DRY_RUN bash -s" <<'REMOTE'
set -euo pipefail
DB="$HOME/revx/data/revx.db"
CUR="$HOME/revx/data/backup-cursor.txt"

if [ ! -f "$CUR" ]; then
    echo "$(date -u +%FT%TZ) курсора выгрузки нет — ничего не удаляю" >&2
    exit 0
fi
read -r book_cur trade_cur < "$CUR"
cutoff=$(( ( $(date -u +%s) - RETAIN_DAYS * 86400 ) * 1000 ))

size_before=$(stat -c %s "$DB")
echo "$(date -u +%FT%TZ) чистка: хранить $RETAIN_DAYS сут, курсор книги $book_cur, сделок $trade_cur"

prune() {
    table="$1"; ts_column="$2"; cursor="$3"
    # ⚠️ ТОЧНЫЙ ПРЕДВАРИТЕЛЬНЫЙ ПОДСЧЁТ УБРАН, И ЭТО НЕ ЭКОНОМИЯ КРАСОТЫ.
    #
    # `count(*) where rowid <= курсор and ts < cutoff` идёт ПОЛНЫМ сканом: на
    # `t_recv_ms` отдельного индекса нет (есть только `(symbol, t_recv_ms)`),
    # поэтому SQLite читает все 13 млн строк, а строка книги на 50 уровнях —
    # почти килобайт. Замер 17.09.2026: запрос не закончился за 15 минут,
    # вычитывая 9.7 ГБ страниц с того же диска, куда в это время пишет сборщик.
    # Прогон платил эту цену КАЖДУЮ НОЧЬ, и как раз в этом окне возникали
    # коллизии за замок.
    #
    # `EXISTS` с тем же условием останавливается на первой подходящей строке, а
    # самые старые строки лежат в начале таблицы (меньший rowid) — то есть
    # находится сразу. Сколько удалено, всё равно известно точнее: считаем по
    # факту в цикле.
    has=$(sqlite3 -readonly "$DB" \
        "select exists(select 1 from $table
            where rowid <= $cursor and $ts_column < $cutoff limit 1);")
    if [ "$has" = "0" ]; then
        echo "  $table: удалять нечего"
        return
    fi
    if [ "$DRY_RUN" = "1" ]; then
        echo "  $table: есть что удалять (точное число не считаем — полный скан)"
        return
    fi
    removed=0
    # ⚠️ Партиями с паузой: один DELETE на миллионы строк держит писательский
    # замок минутами, а на том конце коллектор пишет книгу раз в секунду.
    # Потерянный снимок невосполним, сэкономленная минута — нет.
    #
    # 🔑 ⚠️ BUSY_TIMEOUT ОБЯЗАТЕЛЕН, И ЕГО ОТСУТСТВИЕ СТОИЛО ПОЛОВИНЫ ПРОГОНОВ.
    #
    # У `sqlite3` CLI таймаут ожидания замка по умолчанию НОЛЬ: первая же
    # коллизия со сборщиком (а он пишет девять ног в секунду) возвращает
    # `Error: stepping, database is locked (5)`, и под `set -e` весь прогон
    # умирает, не удалив ничего. 13, 14 и 17.09.2026 чистка падала ровно так, а
    # 15 и 16.09 прошла и отдала 500 и 268 МБ при суточном приросте 600–800 МБ:
    # база выросла с 5.4 ГБ (11.09) до 9.7 ГБ, и диск дошёл до 92%.
    #
    # Тридцать секунд ожидания — против транзакции сборщика в десятки
    # миллисекунд это запас в три порядка, и они НЕ занимают замок: процесс
    # спит, пока писатель не отпустит.
    #
    # ⚠️ Второй предохранитель — НЕ ПАДАТЬ на неудачной партии. Даже с таймаутом
    # замок может не достаться (например, сборщик в это время чекпойнтит WAL на
    # сотню мегабайт), и тогда правильный ответ — подождать и повторить, а не
    # бросить чистку до следующих суток. После пяти неудач подряд выходим по
    # этой таблице с сообщением: дальше пусть смотрит человек, но вторая таблица
    # всё равно будет обработана.
    local attempt=0
    while :; do
        if gone=$(sqlite3 "$DB" \
            "pragma busy_timeout=30000;
             delete from $table where rowid in (select rowid from $table
                where rowid <= $cursor and $ts_column < $cutoff limit $BATCH);
             select changes();" 2>&1); then
            attempt=0
        else
            attempt=$((attempt + 1))
            echo "  $table: партия не прошла ($gone), попытка $attempt из 5"
            if [ "$attempt" -ge 5 ]; then
                echo "  $table: ПРЕРВАНО на замке — удалено не всё"
                return 0
            fi
            sleep $((PAUSE * 10))
            continue
        fi
        # ⚠️ `changes()` печатается последней строкой, а перед ней может лежать
        # предупреждение: берём именно её, а не весь вывод.
        gone=$(printf '%s\n' "$gone" | tail -1)
        [ "$gone" = "0" ] && break
        removed=$((removed + gone))
        sleep "$PAUSE"
    done
    echo "  $table: удалено $removed строк"
}

prune revx_book  t_recv_ms "$book_cur"
prune revx_trade ts_ms     "$trade_cur"

size_after=$(stat -c %s "$DB")
free_pages=$(sqlite3 -readonly "$DB" 'pragma freelist_count;')
page_size=$(sqlite3 -readonly "$DB" 'pragma page_size;')
echo "$(date -u +%FT%TZ) готово: файл $((size_before/1048576)) -> $((size_after/1048576)) МБ, \
свободных страниц $free_pages (= $((free_pages * page_size / 1048576)) МБ под переиспользование)"
df -h "$HOME" | tail -1
REMOTE
