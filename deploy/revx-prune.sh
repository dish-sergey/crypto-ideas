#!/usr/bin/env bash
# Чистка базы стенда на ARM: снести уже вывезенные и достаточно старые строки.
#
# ЗАЧЕМ. С 10.09.2026 книга по трём торгуемым парам собирается на 20 уровней
# вместо пяти, и база растёт примерно на 525 МБ в сутки против прежних 250.
# На диске ARM свободно 19 ГБ — без чистки это чуть больше месяца до отказа
# записи, а отказ записи здесь означает дыру в данных навсегда (принцип 4:
# книгу задним числом не восстановить).
#
# ГЛАВНАЯ ЗАЩИТА — КУРСОР ВЫГРУЗКИ. Удаляется только то, что УЖЕ уехало в
# инкрементную копию на micro: `rowid <= курсор` из backup-cursor.txt. Курсор
# двигает revx-backup.sh, и только после успешного scp. Поэтому даже если
# выгрузка неделю не работала, чистка не тронет ни одной невывезенной строки —
# она просто ничего не удалит. Проверка по возрасту идёт ВТОРЫМ условием, а не
# первым: возраст без курсора удалил бы данные, которых больше нигде нет.
#
# ⚠️ VACUUM НЕ ДЕЛАЕТСЯ, И ЭТО НАМЕРЕННО. Файл после DELETE не уменьшится, но
# освободившиеся страницы SQLite переиспользует под новые вставки — размер
# выходит на полку, а нам ровно это и нужно. Полный VACUUM на базе в гигабайты
# держит писателя и повторяет инцидент 25-26.08.2026, когда `sqlite3 .backup`
# провисел 34 часа и стоил 33 часов книги безвозвратно. Место ради места того
# не стоит.
#
# ════════════════════════════════════════════════════════════════════════════
# 🔑 ПЕРЕПИСАНА 21.09.2026 (задача A77). История болезни и что изменилось.
#
# Чистка была ОТКЛЮЧЕНА 18.09 (A67): книга теряла 15–21 минуту за каждый
# дошедший прогон, и не теряла ничего в сутки, когда чистка падала на замке.
# Причина была найдена верно (спор за писательский замок), а лечение — нет:
# партию срезали с 50 000 строк до 1000, и стало ХУЖЕ, потому что ущерб
# масштабируется ДЛИТЕЛЬНОСТЬЮ спора, а не размером транзакции. Прогон 18.09
# шёл 29 минут на 441 тыс. строк.
#
# Разбор SQL 21.09 показал, где именно уходило время, и это НЕ чтение:
#
#   • план внутреннего запроса — `SEARCH revx_book USING INTEGER PRIMARY KEY
#     (rowid<?)`, и тысяча строк достаётся за 0.01 с. Чтение ни при чём;
#   • `t_recv_ms` МОНОТОНЕН по rowid (проверено в шести точках: rowid 12.16 млн
#     = 04.09, 25.65 млн = 21.09). Значит границу удаления можно найти ДВОИЧНЫМ
#     ПОИСКОМ по первичному ключу — 25 точечных запросов вместо любого скана, —
#     а сами удаления вести НЕПРЕРЫВНЫМИ ДИАПАЗОНАМИ rowid;
#   • у `revx_book` три индекса помимо rowid: PK (symbol, t_sent_ms),
#     `idx_revx_book_snap`, `idx_revx_book_recv`. Каждая удалённая строка — это
#     четыре правки B-деревьев, а `cache_size` был −2000, то есть ДВА МЕГАБАЙТА
#     страничного кэша на базу в 12.8 ГБ. Страницы индексов вымывались и
#     читались с того же диска, куда пишет сборщик;
#   • `synchronous` по умолчанию FULL: fsync на каждую из сотен партий.
#
# Что сделано:
#   1. граница — двоичным поиском, удаление — диапазонами `rowid BETWEEN`;
#   2. `cache_size = −65536` (64 МБ) на время прогона: индексные страницы левого
#      края остаются горячими;
#   3. `synchronous = NORMAL` — это чистка УЖЕ ВЫВЕЗЕННЫХ строк, потерять
#      последние удаления при внезапном отключении питания не страшно;
#   4. 🔑 УСТУПКА ВМЕСТО ПОБЕДЫ: `busy_timeout` снижен с 30 000 до 2000 мс, и
#      перед каждой партией проверяется СВЕЖЕСТЬ КНИГИ. Отстал сборщик больше
#      чем на `MAX_LAG_MS` — чистка ждёт, а не дожимает замок. Прежние тридцать
#      секунд делали её победителем в споре, и платил за это сборщик;
#   5. жёсткий бюджет времени (`BUDGET_SEC`): не успели — уйдём, остаток
#      доберётся завтра. Недоудалённое лучше дыры.
#
# ⚠️ Прежний `database is locked` был не только болезнью, но и предохранителем:
# чистка умирала на первой коллизии и сборщика не трогала. Теперь роль
# предохранителя играет проверка свежести — она мягче и не теряет прогон.
# ════════════════════════════════════════════════════════════════════════════
#
# Запускать С MICRO (ключ есть только в направлении micro -> ARM), после
# выгрузки: cron `45 4 * * *`, то есть через полтора часа после `15 3`.
set -euo pipefail

ARM_HOST="${ARM_HOST:-130.61.31.216}"
ARM_KEY="${ARM_KEY:-$HOME/.ssh/armkey}"
# 11.09.2026: глубина торгуемых пар поднята с 20 уровней до 50 (охват от ±0.4%
# до ±2.5%, нужен для лестницы на ±2% — задача A12). Прирост вырос с 500 МБ до
# ~890 МБ в сутки, и прежние 21 сутки дали бы 18.7 ГБ при 18 свободных.
# Четырнадцать суток — это ~12.5 ГБ, то есть остаётся запас на случай, когда
# выгрузка сломалась: чистка удаляет ТОЛЬКО вывезенное, поэтому при мёртвой
# выгрузке база просто растёт, и запас измеряется в сутках до отказа записи.
RETAIN_DAYS="${RETAIN_DAYS:-14}"     # 14 суток ~ 12.5 ГБ на полке при 18 ГБ свободных
# Строк за одну транзакцию. Десять тысяч непрерывных rowid — это десятки
# миллисекунд под замком (строка книги ~1 КБ, страницы идут подряд), то есть на
# два порядка меньше терпения сборщика. Размер партии больше не главный рычаг:
# главный — свежесть книги перед каждой партией.
BATCH="${BATCH:-10000}"
PAUSE="${PAUSE:-0.2}"                # пауза между партиями, секунд
# Сборщик пишет девять ног в секунду. Две секунды тишины — это уже очередь на
# замке, и чистке пора уступить.
MAX_LAG_MS="${MAX_LAG_MS:-2000}"
BUDGET_SEC="${BUDGET_SEC:-900}"      # общий бюджет прогона, секунд
QUOTA="${QUOTA:-0}"                  # потолок строк за прогон (0 — без потолка)
DRY_RUN="${DRY_RUN:-0}"
REMOTE_TIMEOUT="${REMOTE_TIMEOUT:-1800}"

ssh_opts=(-i "$ARM_KEY" -o BatchMode=yes -o ConnectTimeout=20)

ssh "${ssh_opts[@]}" "ubuntu@$ARM_HOST" \
    "flock -n /tmp/revx-prune.lock timeout -k 60 $REMOTE_TIMEOUT env \
     RETAIN_DAYS=$RETAIN_DAYS BATCH=$BATCH PAUSE=$PAUSE DRY_RUN=$DRY_RUN \
     MAX_LAG_MS=$MAX_LAG_MS BUDGET_SEC=$BUDGET_SEC QUOTA=$QUOTA bash -s" <<'REMOTE'
set -euo pipefail
DB="$HOME/revx/data/revx.db"
CUR="$HOME/revx/data/backup-cursor.txt"
STARTED=$(date -u +%s)

if [ ! -f "$CUR" ]; then
    echo "$(date -u +%FT%TZ) курсора выгрузки нет — ничего не удаляю" >&2
    exit 0
fi
read -r book_cur trade_cur < "$CUR"
cutoff=$(( ( $(date -u +%s) - RETAIN_DAYS * 86400 ) * 1000 ))

size_before=$(stat -c %s "$DB")
echo "$(date -u +%FT%TZ) чистка: хранить $RETAIN_DAYS сут, курсор книги $book_cur, сделок $trade_cur"

# Общие настройки соединения. cache_size в КИЛОБАЙТАХ со знаком минус.
PRAGMAS="pragma busy_timeout=2000; pragma cache_size=-65536; pragma synchronous=NORMAL;"

# Возраст самой свежей строки книги, мс. Один seek в правый край rowid-дерева:
# max(t_recv_ms) искать нельзя — по нему нет отдельного индекса, а rowid растёт
# вместе со временем (проверено).
# ⚠️ Время берётся с МИЛЛИСЕКУНДАМИ: `strftime('%s','now')` режет до секунды, и
# отставание получало ошибку до 1000 мс при пороге в 2000 — в первом же сухом
# прогоне оно вышло отрицательным (−510 мс), чего быть не может.
book_lag_ms() {
    sqlite3 -readonly "$DB" \
        "select cast((julianday('now') - 2440587.5) * 86400000 as integer)
                - (select t_recv_ms from revx_book order by rowid desc limit 1);" 2>/dev/null || echo 999999
}

# Наибольший rowid со временем строго меньше cutoff — двоичным поиском.
# ⚠️ Законно ровно потому, что t_recv_ms монотонен по rowid. Если однажды это
# перестанет быть правдой, защитой останется условие по времени в самом DELETE:
# граница задаёт только ОБЪЁМ работы, а не право удалять.
boundary() {
    table="$1"; ts_column="$2"; hi_limit="$3"
    lo=$(sqlite3 -readonly "$DB" "select min(rowid) from $table;")
    hi=$(sqlite3 -readonly "$DB" "select max(rowid) from $table;")
    [ -z "$lo" ] && { echo 0; return; }
    [ "$hi" -gt "$hi_limit" ] && hi=$hi_limit
    ans=0
    while [ "$lo" -le "$hi" ]; do
        mid=$(( (lo + hi) / 2 ))
        # Ближайшая существующая строка не правее mid: rowid'ы после удалений
        # разрежены, и точное попадание не гарантировано.
        row=$(sqlite3 -readonly "$DB" \
            "select rowid, $ts_column from $table where rowid <= $mid order by rowid desc limit 1;")
        if [ -z "$row" ]; then
            lo=$(( mid + 1 ))
            continue
        fi
        r_id=${row%%|*}
        r_ts=${row##*|}
        if [ "$r_ts" -lt "$cutoff" ]; then
            ans=$r_id
            lo=$(( mid + 1 ))
        else
            hi=$(( r_id - 1 ))
        fi
    done
    echo "$ans"
}

prune() {
    table="$1"; ts_column="$2"; cursor="$3"
    bound=$(boundary "$table" "$ts_column" "$cursor")
    if [ "$bound" -le 0 ]; then
        echo "  $table: удалять нечего"
        return 0
    fi
    first=$(sqlite3 -readonly "$DB" "select min(rowid) from $table;")
    echo "  $table: граница rowid $bound (курсор $cursor), от $first — примерно $(( (bound - first + 1) )) строк"
    if [ "$DRY_RUN" = "1" ]; then
        return 0
    fi
    removed=0
    lag_max=0
    waits=0
    lo=$first
    while [ "$lo" -le "$bound" ]; do
        if [ $(( $(date -u +%s) - STARTED )) -ge "$BUDGET_SEC" ]; then
            echo "  $table: бюджет времени исчерпан, остановился на rowid $lo"
            break
        fi
        if [ "$QUOTA" -gt 0 ] && [ "$removed" -ge "$QUOTA" ]; then
            echo "  $table: выбрана квота $QUOTA строк, остановился на rowid $lo"
            break
        fi
        # 🔑 УСТУПКА: сначала смотрим, пишет ли сборщик, и только потом лезем за
        # замком. Отстал — ждём. Это и есть замена тридцатисекундному таймауту,
        # который раньше делал чистку победителем спора.
        lag=$(book_lag_ms)
        if [ "$lag" -gt "$lag_max" ] 2>/dev/null; then
            lag_max=$lag
        fi
        if [ "$lag" -gt "$MAX_LAG_MS" ] 2>/dev/null; then
            waits=$((waits + 1))
            if [ "$waits" -gt 20 ]; then
                echo "  $table: сборщик отстаёт ($lag мс) двадцать раз подряд — ухожу"
                break
            fi
            sleep 2
            continue
        fi
        waits=0
        end=$(( lo + BATCH - 1 ))
        [ "$end" -gt "$bound" ] && end=$bound
        # Условие по времени оставлено НАМЕРЕННО: диапазон rowid задаёт объём
        # работы, а право удалять даёт курсор и возраст.
        if gone=$(sqlite3 "$DB" "$PRAGMAS
             delete from $table
              where rowid between $lo and $end and $ts_column < $cutoff;
             select changes();" 2>&1); then
            gone=$(printf '%s\n' "$gone" | tail -1)
            removed=$(( removed + gone ))
            lo=$(( end + 1 ))
            sleep "$PAUSE"
        else
            # Замок не достался — это НОРМА, а не авария: ждём и повторяем тот
            # же диапазон. Под `set -e` тут нельзя падать, иначе один спор
            # отменяет весь прогон.
            echo "  $table: партия $lo–$end не прошла ($gone), жду"
            sleep 2
        fi
    done
    echo "  $table: удалено $removed строк, максимальное отставание книги $lag_max мс"
}

lag0=$(book_lag_ms)
echo "  отставание книги до начала: $lag0 мс"
prune revx_book  t_recv_ms "$book_cur"
prune revx_trade ts_ms     "$trade_cur"
lag1=$(book_lag_ms)

size_after=$(stat -c %s "$DB")
free_pages=$(sqlite3 -readonly "$DB" 'pragma freelist_count;')
page_size=$(sqlite3 -readonly "$DB" 'pragma page_size;')
echo "$(date -u +%FT%TZ) готово за $(( $(date -u +%s) - STARTED )) с: файл $((size_before/1048576)) -> $((size_after/1048576)) МБ, \
свободных страниц $free_pages (= $((free_pages * page_size / 1048576)) МБ под переиспользование), \
отставание книги на выходе $lag1 мс"
df -h "$HOME" | tail -1
REMOTE
